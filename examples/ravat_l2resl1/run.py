#!/usr/bin/env python3
"""Offline regional L2resL1 pipeline: selected LP CSVs or a labelled synthetic demo."""
import argparse
import hashlib
import json
from pathlib import Path
import sys

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'src'))
from gravmagpy import (load_lpmag_csv, along_track_differences, regional_monopole_grid,
                       fit_ravat_l2resl1, predict_ravat_field, save_ravat_fit, spherical_to_cartesian)
from gravmagpy.ravat import ellipsoid_points, load_moonbroom_wake


def synthetic_observations():
    """Independent analytic dipole truth, not generated by the monopole fitter."""
    latitudes, longitudes, tracks = [], [], []
    for k, lon in enumerate(np.linspace(300.5,303.5,9)):
        lat = np.linspace(5.5,9.5,40)
        latitudes.extend(lat)
        longitudes.extend(np.full(len(lat),lon))
        tracks.extend(np.full(len(lat),k))
    xyz = spherical_to_cartesian(latitudes,longitudes,1737.4+30)
    center = spherical_to_cartesian(7.5,302,1737.4-12)
    moment = np.array([1.0,-1.3,0.7])*1e12
    delta = (xyz-center)*1000
    r = np.linalg.norm(delta,axis=1)
    field = 100*(3*(delta@moment)[:,None]*delta/r[:,None]**5-moment/r[:,None]**3)
    rng = np.random.default_rng(20261022)
    sigma = 0.03
    observed = field+rng.normal(0,sigma,field.shape)
    # A constant spherical-component offset would cancel exactly. Here add small
    # Cartesian pass offsets, whose local-frame rotation does not cancel exactly.
    offsets = rng.normal(0,0.1,(9,3))
    observed += offsets[np.asarray(tracks)]
    times = pd.Timestamp('1999-01-01T00:00:00Z')+pd.to_timedelta(np.arange(len(xyz))*5,unit='s')
    table = pd.DataFrame({'utc':times,'source_file':[f'synthetic_pass_{k}' for k in tracks],
                          'source_row':np.tile(np.arange(40),9)})
    return dict(xyz_km=xyz,field_nt=observed,sigma_nt=sigma,radius_km=1737.4,
                frame='planet_fixed',table=table,track_ids=tracks)


def validate_synthetic(solution):
    """Unseen longitudes: report difference and absolute-vector errors separately."""
    from gravmagpy.ravat import spherical_basis
    lat, lon = np.meshgrid(np.linspace(5.5,9.5,40), np.linspace(300.6875,303.3125,8))
    xyz = spherical_to_cartesian(lat.ravel(),lon.ravel(),1767.4)
    center = spherical_to_cartesian(7.5,302,1725.4)
    delta = (xyz-center)*1000
    radius = np.linalg.norm(delta,axis=1)
    moment = np.array([1.,-1.3,0.7])*1e12
    truth = 100*(3*(delta@moment)[:,None]*delta/radius[:,None]**5-moment/radius[:,None]**3)
    expected = np.einsum('nci,ni->nc',spherical_basis(xyz),truth).reshape(8,40,3)
    actual = predict_ravat_field(xyz,solution)['rtp_nt'].reshape(8,40,3)
    return dict(heldout_difference_rmse_nt=float(np.sqrt(np.mean((np.diff(actual,axis=1)-np.diff(expected,axis=1))**2))),
        heldout_absolute_vector_rmse_nt=float(np.sqrt(np.mean((actual-expected)**2))),
        note='Differences-only regional fitting can match gradients while retaining substantial absolute-field error; these are unseen synthetic tracks, not a real-data validation.')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--demo',action='store_true',help='synthetic recovery only; not a Ravat data reproduction')
    parser.add_argument('--observations',nargs='+',type=Path,help='already selected, body-fixed LP vector CSVs')
    parser.add_argument('--wake-dir',type=Path,help='MoonBroom filtered_wake root or its 90-percentile subdirectory')
    parser.add_argument('--selection-confirmed',action='store_true',help='confirm paper-style wake/tail, altitude, and quality selection was applied upstream')
    parser.add_argument('--output',type=Path,default=ROOT/'examples/ravat_l2resl1/output')
    parser.add_argument('--bounds',nargs=4,type=float,default=[299.,4.,305.,11.],metavar=('WEST','SOUTH','EAST','NORTH'))
    parser.add_argument('--spacing-km',type=float,default=15.)
    parser.add_argument('--depth-km',type=float,default=10.)
    parser.add_argument('--alpha-l2',type=float)
    parser.add_argument('--alpha-l1',type=float)
    parser.add_argument('--data-mode',choices=['differences','vectors','vectors_and_differences'],default='differences')
    parser.add_argument('--pairing',choices=['adjacent','disjoint'],default=None,help='default: all adjacent pairs for differences-only, disjoint otherwise')
    parser.add_argument('--epsilon-nt',type=float,default=0.1)
    parser.add_argument('--sigma-nt',type=float,default=1.)
    parser.add_argument('--iterations',type=int,default=200)
    parser.add_argument('--memory-mib',type=float,default=512)
    parser.add_argument('--cadence-s',type=float,default=5.)
    parser.add_argument('--plot',action='store_true')
    args = parser.parse_args()
    if sum([args.demo, bool(args.observations), args.wake_dir is not None]) != 1:
        parser.error('choose one of --demo, --observations, or --wake-dir')
    if args.observations and not args.selection_confirmed:
        parser.error('real data require --selection-confirmed after upstream paper-style selection; see docs/ravat.md')
    if not args.demo and (args.alpha_l2 is None or args.alpha_l1 is None):
        parser.error('provide both damping parameters; paper tuning is not transferable to this normalization')
    alpha_l2 = args.alpha_l2 if args.alpha_l2 is not None else 0.2
    alpha_l1 = args.alpha_l1 if args.alpha_l1 is not None else 2.0
    if args.demo:
        observations = synthetic_observations()
    elif args.wake_dir is not None:
        observations = load_moonbroom_wake(args.wake_dir, bounds=args.bounds, sigma_nt=args.sigma_nt)
    else:
        observations = load_lpmag_csv(args.observations, wake_only=False,
            sigma_nt=args.sigma_nt, altitude_range_km=(12,48))
    pairing = args.pairing or ('adjacent' if args.data_mode == 'differences' else 'disjoint')
    differences = along_track_differences(observations,cadence_s=args.cadence_s,pairing=pairing)
    grid = regional_monopole_grid(args.bounds,spacing_km=args.spacing_km,depth_km=args.depth_km)
    print(f'{len(differences["pairs"])} along-track differences; {len(grid["source_xyz_km"])} equivalent sources',flush=True)
    fit = fit_ravat_l2resl1(differences,grid['source_xyz_km'],grid['surface_xyz_km'],
        area_weights=grid['area_weights'],alpha_l2=alpha_l2,alpha_l1=alpha_l1,
        epsilon_nt=args.epsilon_nt,max_iterations=args.iterations,max_memory_mib=args.memory_mib, data_mode=args.data_mode)
    args.output.mkdir(parents=True,exist_ok=True)
    save_ravat_fit(fit,differences,args.output)
    observations['table'].to_csv(args.output/'observation_index.csv',index=False)
    grid['table'].to_csv(args.output/'source_grid.csv',index=False)
    west,south,east,north = grid['table'].lon_deg.min(),args.bounds[1],grid['table'].lon_deg.max(),args.bounds[3]
    if args.bounds[2] < args.bounds[0]:
        east = args.bounds[2]+360
    else:
        west,east = args.bounds[0],args.bounds[2]
    lons,lats = np.meshgrid(np.linspace(west,east,101),np.linspace(south,north,101))
    xyz = ellipsoid_points(lats.ravel(),lons.ravel())
    surface = pd.DataFrame({'lon_deg':lons.ravel(),'lat_deg':lats.ravel()})
    for part in ('baseline','correction','total'):
        prediction = predict_ravat_field(xyz,fit,part=part)
        for j,key in enumerate(('br','btheta','bphi')):
            surface[f'{part}_{key}_nt'] = prediction['rtp_nt'][:,j]
        surface[f'{part}_magnitude_nt'] = prediction['total_nt']
    surface.to_csv(args.output/'surface_field.csv.gz',index=False)
    metadata = vars(args).copy()
    metadata['output'] = str(args.output)
    metadata['wake_dir'] = str(args.wake_dir) if args.wake_dir is not None else None
    metadata['selection'] = observations.get('selection')
    metadata['preprocessing'] = differences['preprocessing']
    pd.DataFrame(observations.get('report', [])).to_csv(args.output/'input_report.csv',index=False)
    metadata['observations'] = [str(p) for p in args.observations or []]
    metadata['alpha_l2'],metadata['alpha_l1'] = alpha_l2,alpha_l1
    input_paths = [Path(p) for p in observations['table'].source_file.unique()] if not args.demo else []
    metadata['input_sha256'] = {str(p):hashlib.sha256(p.read_bytes()).hexdigest() for p in input_paths}
    metadata['interpretation'] = 'synthetic demonstration' if args.demo else 'method replica with user-selected observations; not exact published inversion'
    metadata['numpy_version'],metadata['pandas_version'] = np.__version__,pd.__version__
    (args.output/'run.json').write_text(json.dumps(metadata,indent=2)+'\n')
    rmse = float(np.sqrt(np.mean(fit['residual_difference_nt']**2)))
    print('Data mode:', fit['data_mode'], '| Independent whitened rows:', fit['independent_data_rows'])
    print('Vector RMSE (nT):', np.sqrt(np.mean(fit['residual_vector_nt']**2)))
    print(f'Difference RMSE: {rmse:.6g} nT; L2 converged: {fit["converged_l2"]}; residual L1 converged: {fit["converged_l1"]}')
    if not fit['success']:
        print('Iteration limit/stall reached; inspect history_l2.csv and history_l1.csv before interpreting the map.')
    if args.demo:
        validation = validate_synthetic(fit)
        (args.output/'synthetic_validation.json').write_text(json.dumps(validation,indent=2)+'\n')
        print('Unseen synthetic-track validation:', validation)
    if args.plot:
        import matplotlib.pyplot as plt
        fig,axes = plt.subplots(4,3,figsize=(14,15),constrained_layout=True)
        for row,component in enumerate(('br','btheta','bphi','magnitude')):
            columns = [f'{part}_{component}_nt' for part in ('baseline','correction','total')]
            limit = max(np.max(np.abs(surface[column])) for column in columns)
            for ax,part,column in zip(axes[row],('L2 baseline','L1 residual correction','Vector sum'),columns):
                total = component == 'magnitude'
                im = ax.pcolormesh(lons,lats,surface[column].to_numpy().reshape(lons.shape),shading='auto',
                    cmap='viridis' if total else 'RdBu_r',vmin=0 if total else -limit,vmax=limit)
                ax.set(title=f'{part}: {component}',xlabel='Longitude (°E)',ylabel='Latitude (°)')
                fig.colorbar(im,ax=ax,label='nT')
        fig.suptitle('Synthetic L2resL1 demonstration' if args.demo else 'Regional L2resL1 method replica')
        fig.savefig(args.output/'surface_stages.png',dpi=160)
        plt.close(fig)
    print('Saved',args.output)


if __name__ == '__main__':
    main()
